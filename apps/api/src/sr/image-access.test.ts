import { afterEach, expect, it, vi } from 'vitest'
import { assertFileAccess } from './access.js'

afterEach(() => vi.restoreAllMocks())
function database(requesterId: string, kind = 'ai_output') {
  const results = [[{ isBusinessOwner: true }], [{ id: 'image', kind, originSrId: 'sr', uploadedBy: 'system-owner' }],
    [{ id: 'sr', requesterId, status: 'draft' }], [{ isBusinessOwner: true }], []]
  return { select: () => ({ from: () => ({ where: async () => results.shift(),
    innerJoin() { return this } }) }) } as never
}

it('lets an SR requester read ai_output generated by a different actor', async () => {
  await expect(assertFileAccess(database('bo'), 'bo', 'image')).resolves.toBeUndefined()
})

it('rejects another BO and preserves upload ownership rules for ordinary SR attachments', async () => {
  await expect(assertFileAccess(database('other-bo'), 'bo', 'image')).rejects.toMatchObject({ status: 403 })
  await expect(assertFileAccess(database('bo', 'sr_attachment'), 'bo', 'image')).rejects.toMatchObject({ status: 403 })
})
