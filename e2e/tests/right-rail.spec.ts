import { expect, test, type Page } from '@playwright/test'
import { linkedMaterialsToggle, openWorkTool } from './materials.js'

async function setup(page: Page) {
  expect((await page.request.post('/api/auth/signup', { data: { loginId: `rail-${crypto.randomUUID().slice(0, 16)}`, name: '레일 검증', password: 'e2e-password-1234' } })).ok()).toBe(true)
  const assistants = await (await page.request.get('/api/assistants')).json() as Array<{ id: string; status: string }>
  const task = await (await page.request.post('/api/tasks', { data: { assistantId: assistants.find(item => item.status === 'open')!.id, tags: [`rail-${crypto.randomUUID()}`] } })).json() as { id: string }
  expect((await page.request.post('/api/files', { multipart: { originTaskId: task.id, file: { name: 'rail.txt', mimeType: 'text/plain', buffer: Buffer.from('자료 후보') } } })).ok()).toBe(true)
  await page.goto(`/c/${task.id}`)
  return task
}

test('넓은 화면: 56px 상시 레일·미확인 배지·360px push와 유일한 입구', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  const task = await setup(page)
  const rail = page.getByRole('navigation', { name: '업무 도구' })
  const materials = linkedMaterialsToggle(page)
  await expect(rail.getByRole('button')).toHaveCount(4)
  await expect(materials).toContainText('새 1')
  await expect(materials).toHaveAttribute('aria-pressed', 'false')
  expect((await rail.boundingBox())!.width).toBe(56)
  await expect(page.getByRole('button', { name: /^연결 자료(?:\(\d+\))?$/ })).toHaveCount(0)
  await page.getByRole('button', { name: '더 보기', exact: true }).click()
  for (const name of ['체크리스트 열기', '메모 열기', '활동 이력 열기']) await expect(page.getByRole('menuitem', { name, exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')
  const before = await page.getByRole('region', { name: '대화', exact: true }).boundingBox()
  await materials.click()
  const panel = page.getByRole('complementary', { name: '#태그·SR 연결 자료' })
  await expect(panel).toBeVisible()
  expect((await panel.boundingBox())!.width).toBe(360)
  const after = await page.getByRole('region', { name: '대화', exact: true }).boundingBox()
  expect(before!.width - after!.width).toBe(360)
  await expect(materials).not.toContainText('새 ')
  await expect(panel.getByRole('tab')).toHaveCount(4)
  await openWorkTool(page, '메모')
  await page.getByRole('textbox', { name: '메모 본문' }).fill('다음에 볼 메모')
  await page.reload()
  await expect(page.getByRole('tab', { name: '메모', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('textbox', { name: '메모 본문' })).toHaveValue('다음에 볼 메모')
  await page.getByRole('button', { name: '접기', exact: true }).click()
  await expect(rail.getByRole('button', { name: '메모', exact: true })).toBeFocused()
  expect((await page.request.post('/api/files', { multipart: { originTaskId: task.id, file: { name: 'new.txt', mimeType: 'text/plain', buffer: Buffer.from('새 후보') } } })).ok()).toBe(true)
  await expect(materials).toContainText('새 1')
  await expect(materials).toHaveAttribute('aria-pressed', 'false')
  await expect(panel).toBeHidden()
})

test('좁은 화면: 하단 4칸 바·70% 이하 시트·닫기 후 진입점 포커스', async ({ page }) => {
  await page.setViewportSize({ width: 900, height: 800 })
  await setup(page)
  const rail = page.getByRole('navigation', { name: '업무 도구' })
  await expect(rail).toHaveAttribute('data-layout', 'bottom')
  const entries = await rail.getByRole('button').all()
  expect(entries).toHaveLength(4)
  const boxes = await Promise.all(entries.map(entry => entry.boundingBox()))
  for (const box of boxes) { expect(box!.y).toBe(boxes[0]!.y); expect(box!.width).toBeCloseTo(boxes[0]!.width, 0) }
  await expect(page.getByRole('dialog', { name: '대화 보조 패널' })).toHaveCount(0)
  const entry = rail.getByRole('button', { name: '메모', exact: true })
  await entry.click()
  const sheet = page.getByRole('dialog', { name: '대화 보조 패널' })
  await expect(sheet).toBeVisible()
  const body = await page.getByTestId('task-body').boundingBox()
  const bounds = await sheet.boundingBox()
  expect(bounds!.height).toBeLessThanOrEqual(body!.height * 0.7 + 1)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(boxes[0]!.y + 1)
  await sheet.getByRole('textbox', { name: '메모 본문' }).fill('화면을 넓혀도 유지')
  await page.setViewportSize({ width: 1440, height: 800 })
  await expect(page.getByRole('complementary', { name: '#태그·SR 연결 자료' })).toBeVisible()
  await expect(page.getByRole('textbox', { name: '메모 본문' })).toHaveValue('화면을 넓혀도 유지')
  await page.setViewportSize({ width: 900, height: 800 })
  await sheet.getByRole('button', { name: '접기', exact: true }).click()
  await expect(sheet).toBeHidden()
  await expect(entry).toBeFocused()
})
