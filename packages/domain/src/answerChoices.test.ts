import { describe, expect, it } from 'vitest'
import { detectAnswerChoices } from './answerChoices.js'

describe('detectAnswerChoices', () => {
  it.each([
    ['질문과 번호', '어느 쪽인가요?\n1. 빠르게\n2. 자세하게', ['빠르게', '자세하게'], 'question'],
    ['괄호 번호', '다음 중 선택\n1) 요약\n2) 원문', ['요약', '원문'], 'list'],
    ['원문자', '① 요약\n② 원문', ['요약', '원문'], 'list'],
    ['영문', 'Which one?\nA. Summary\nB. Details', ['Summary', 'Details'], 'question'],
    ['한글', '가. 요약\n나. 상세', ['요약', '상세'], 'list'],
    ['하이픈', '- 요약\n- 상세\n', ['요약', '상세'], 'list'],
    ['별표와 빈 줄', '* 요약\n\n* 상세', ['요약', '상세'], 'list'],
    ['코드 바로 뒤 목록', '```txt\n- 코드 예시\n- 다른 예시\n```\n- 요약\n- 상세', ['요약', '상세'], 'list'],
    ['최대 여섯 개', '1. 가\n2. 나\n3. 다\n4. 라\n5. 마\n6. 바', ['가', '나', '다', '라', '마', '바'], 'list'],
    ['80자 경계', `- ${'가'.repeat(80)}\n- 짧음`, ['가'.repeat(80), '짧음'], 'list'],
    ['이전 코드와 표는 무관', '```txt\n- 코드\n```\n\n| 표 | 값 |\n| --- | --- |\n\n골라주세요?\n- 요약\n- 상세', ['요약', '상세'], 'question'],
  ])('%s 목록의 본문과 질문 신호를 추출한다', (_, text, items, confidence) => {
    expect(detectAnswerChoices(text)).toEqual({ items, confidence })
  })

  it.each([
    ['닫힌 코드', '```md\n1. 요약\n2. 상세\n```'],
    ['열린 코드', '~~~md\n1. 요약\n2. 상세'],
    ['들여쓴 코드', '    - 요약\n    - 상세'],
    ['표', '| 선택 | 설명 |\n| --- | --- |\n| 1 | 요약 |\n| 2 | 상세 |'],
    ['표를 담은 항목', '- 요약 | 설명\n- 상세 | 설명'],
    ['81자 항목', `- ${'가'.repeat(81)}\n- 짧음`],
    ['하나', '선택?\n1. 요약'],
    ['일곱', '1. 가\n2. 나\n3. 다\n4. 라\n5. 마\n6. 바\n7. 사'],
    ['중간 목록', '1. 요약\n2. 상세\n\n참고해서 알려주세요.'],
    ['문장만', '어떤 방식이 좋나요?'],
    ['여러 줄 항목', '- 첫 항목\n  이어지는 설명\n- 두 번째'],
    ['중첩 목록', '- 상위\n  - 요약\n  - 상세'],
    ['들여쓰기 없는 연속 설명', '1. 첫 항목\n이어지는 설명\n2. 두 번째\n3. 세 번째'],
    ['긴 번호 부모의 중첩 목록', '100. 상위\n  - 요약\n  - 상세'],
    ['빈 문자열', ''],
  ])('%s은 선택지로 취급하지 않는다', (_, text) => {
    expect(detectAnswerChoices(text)).toBeNull()
  })
})
